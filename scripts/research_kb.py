#!/usr/bin/env python3
"""research_kb.py - step 2 of the flow: pull the relevant knowledge-base sections into the project's research note.

    python3 scripts/research_kb.py <project> --topic "amazon forest fusion" --tags arabic,afro,tamil,ambience [--docs 3]
        [--sounds rain_roof,frog_chorus]     # one "Real-world references" section per sound the score will use

Ranks knowledgebase/*.md by how often the tags/topic words appear (file name, document_id, title, body), copies the
sections that mention them into reports/research_<topic>.md with each document_id cited, and leaves an empty
"Web research" section. The agent adds web sources (URL + takeaway) there; pipeline.py blocks until it has a URL.
With --sounds it also writes a "Real-world references: <slug>" section per ambience or effect: two real sources (a paper,
a field-recording page, a measured spectrum), their licence, and the values taken. The preset lists the slug in "sources".
"""
import argparse
import re
import sys
import time
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
KB = SKILL / 'knowledgebase'
SECTION = re.compile(r'^(#{2,3})\s+(.*)$', re.M)


def read_doc(p):
    text = p.read_text(encoding='utf-8', errors='replace')
    m = re.search(r'document_id:\s*["\']?([A-Za-z0-9_\-.]+)', text[:2500])
    title = next((l.lstrip('# ').strip() for l in text.splitlines() if l.startswith('# ')), p.stem)
    return text, (m.group(1) if m else None), title


def sections(text):
    marks = list(SECTION.finditer(text))
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        yield m.group(2).strip(), text[m.end():end].strip()


def terms_of(topic, tags):
    words = [w for w in re.split(r'[^a-z0-9]+', (topic + ' ' + ' '.join(tags)).lower()) if len(w) > 2]
    return sorted(set(words))


def rank(terms):
    scored = []
    for p in sorted(KB.glob('*.md')):
        if p.name == 'README.md':
            continue
        text, doc_id, title = read_doc(p)
        if not doc_id:
            continue
        low = text.lower()
        head = (p.name + ' ' + doc_id + ' ' + title).lower()
        s = sum(min(low.count(t), 40) + 25 * (t in head) for t in terms)
        if s:
            scored.append((s, p, text, doc_id, title))
    return sorted(scored, key=lambda x: -x[0])


def excerpt(body, terms, max_lines=22):
    lines = [l for l in body.splitlines() if l.strip()]
    return '\n'.join(lines[:max_lines]) + ('\n...' if len(lines) > max_lines else '')


def build(topic, tags, ndocs, sounds=()):
    terms = terms_of(topic, tags)
    hits = rank(terms)[:ndocs]
    if not hits:
        names = ', '.join(p.stem for p in sorted(KB.glob('*.md')) if p.name != 'README.md')
        sys.exit(f'no knowledge-base document matches {terms}. Documents: {names}\n(see knowledgebase/README.md for the index)')
    out = [f'# Research: {topic}', '',
           f'Generated by research_kb.py on {time.strftime("%Y-%m-%d")}. Tags: {", ".join(tags) or "-"}. '
           'Values below are copied from the knowledge base; check them against the web sources.', '', '## Knowledge base', '']
    for score, p, text, doc_id, title in hits:
        out += [f'### {title}', f'- file: `knowledgebase/{p.name}`', f'- document_id: `{doc_id}`', '']
        picked = [(h, b) for h, b in sections(text) if any(t in (h + ' ' + b).lower() for t in terms)]
        for h, b in picked[:6]:
            out += [f'#### {h}', excerpt(b, terms), '']
        if not picked:
            out += ['(no section mentions the tags; read the document whole)', '']
    for snd in sounds:
        slug = re.sub(r'[^a-z0-9]+', '_', snd.lower()).strip('_')
        out += [f'## Real-world references: {slug}', '',
                '_TODO: at least two sources of the REAL sound: a paper (drop sizes, call rates, spectra), the page of a field recording '
                '(place, equipment, conditions), or a measured spectrum. One URL per line, with the value taken from it._', '',
                '- URL: _TODO_', '- URL: _TODO_', 'Licence: _TODO: analysed only / may keep / which licence_',
                'Measured: _TODO: centroid, 90% rolloff, band shares, event rate (scripts/ambience_reference.py measure), '
                'or write: No measurement found: ESTIMATE <reason>_', '']
    out += ['## Web research', '',
            '_TODO: add sources, one per line: URL + one-line takeaway (TinyFish search / fetch_content)._', '',
            '## Decisions taken from this research', '',
            '_TODO: which scale/mode, tempo, rhythm pattern, instruments and formants the presets will use, and why._', '']
    return '\n'.join(out), [h[3] for h in hits]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('project')
    ap.add_argument('--topic', required=True)
    ap.add_argument('--tags', default='', help='comma list: cultures, genres, techniques (arabic,tamil,ambience)')
    ap.add_argument('--sounds', default='', help='comma list of sounds the score uses (rain_roof,frog_chorus): one references section each')
    ap.add_argument('--docs', type=int, default=3, help='how many knowledge-base documents to cite')
    a = ap.parse_args()
    proj = Path(a.project)
    if not (proj / 'reports').is_dir():
        sys.exit(f'{proj}/reports not found. Create the project first: setup_project.py --new-project {proj} --title "<T>"')
    tags = [t.strip() for t in a.tags.split(',') if t.strip()]
    md, ids = build(a.topic, tags, a.docs, [x.strip() for x in a.sounds.split(',') if x.strip()])
    slug = re.sub(r'[^a-z0-9]+', '_', a.topic.lower()).strip('_') or 'topic'
    out = proj / 'reports' / f'research_{slug}.md'
    out.write_text(md, encoding='utf-8')
    print(f'wrote {out}')
    print('cited document_ids:', ', '.join(ids))
    print('next: add web sources (URL + takeaway) under "Web research", then fill direction/ and presets/')


if __name__ == '__main__':
    main()
